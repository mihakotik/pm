package installer

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// GenerateBwrapWrapper creates an executable wrapper script content
// that invokes the foreign binary inside an isolated bubblewrap environment.
func GenerateBwrapWrapper(provider, pkgName, binaryName, targetBinPath string) (string, error) {
	if provider == "" || pkgName == "" || binaryName == "" || targetBinPath == "" {
		return "", fmt.Errorf("invalid arguments: provider, pkgName, binaryName and targetBinPath must not be empty")
	}

	optDir := fmt.Sprintf("/opt/pm/%s/%s", provider, pkgName)
	if !strings.HasPrefix(targetBinPath, "/") {
		targetBinPath = "/" + targetBinPath
	}
	fullTargetPath := optDir + targetBinPath

	script := fmt.Sprintf(`#!/bin/sh
# Generated by pm for foreign package %s (%s)
# Sandbox wrapper executing binary within isolated bubblewrap environment

TARGET_BIN="%s"
OPT_DIR="%s"

if [ ! -f "$TARGET_BIN" ]; then
    echo "pm: foreign binary not found: $TARGET_BIN" >&2
    exit 127
fi

BWRAP_BIN=$(command -v bwrap 2>/dev/null || echo "/usr/bin/bwrap")
if [ ! -x "$BWRAP_BIN" ]; then
    echo "pm: bubblewrap is required to execute foreign packages safely" >&2
    exit 127
fi

FOREIGN_LIB="$OPT_DIR/usr/lib:$OPT_DIR/usr/lib64:$OPT_DIR/lib:$OPT_DIR/lib64"
FOREIGN_PATH="$OPT_DIR/usr/bin:$OPT_DIR/bin:$PATH"

EXTRA_ARGS=""
[ -d /home ] && EXTRA_ARGS="$EXTRA_ARGS --bind /home /home"
[ -d /run ] && EXTRA_ARGS="$EXTRA_ARGS --bind /run /run"
[ -d /sys ] && EXTRA_ARGS="$EXTRA_ARGS --ro-bind /sys /sys"

exec "$BWRAP_BIN" \
    --ro-bind / / \
    --ro-bind "$OPT_DIR" "$OPT_DIR" \
    --dev /dev \
    --proc /proc \
    --bind /tmp /tmp \
    $EXTRA_ARGS \
    --setenv LD_LIBRARY_PATH "$FOREIGN_LIB:$LD_LIBRARY_PATH" \
    --setenv PATH "$FOREIGN_PATH" \
    "$TARGET_BIN" "$@"
`, pkgName, provider, fullTargetPath, optDir)

	return script, nil
}

// CreateWrapperFile writes the generated wrapper script to destBinDir/binaryName with 0755 permissions.
func CreateWrapperFile(destBinDir, provider, pkgName, binaryName, targetBinPath string) (string, error) {
	script, err := GenerateBwrapWrapper(provider, pkgName, binaryName, targetBinPath)
	if err != nil {
		return "", err
	}

	if err := os.MkdirAll(destBinDir, 0755); err != nil {
		return "", fmt.Errorf("failed to create directory %s: %w", destBinDir, err)
	}

	wrapperPath := filepath.Join(destBinDir, binaryName)
	if err := os.WriteFile(wrapperPath, []byte(script), 0755); err != nil {
		return "", fmt.Errorf("failed writing wrapper script %s: %w", wrapperPath, err)
	}

	return wrapperPath, nil
}
